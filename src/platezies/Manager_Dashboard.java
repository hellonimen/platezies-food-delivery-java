    private void jToggleButton1_closeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1_closeActionPerformed
        // TODO add your handling code here:
        int response = JOptionPane.showConfirmDialog(this, 
                "Are you sure you want to logout?", 
                "Confirm Logout", 
                JOptionPane.YES_NO_OPTION, 
                JOptionPane.QUESTION_MESSAGE);

        if (response == JOptionPane.YES_OPTION) {
            JOptionPane.showMessageDialog(this, "Successfully logged out.", 
                                          "Logout", 
                                          JOptionPane.INFORMATION_MESSAGE);

            Login loginFrame = new Login(); 
            loginFrame.setVisible(true); 
            JFrame parentFrame = (JFrame) javax.swing.SwingUtilities.getWindowAncestor(this);
            if (parentFrame != null) {
                parentFrame.dispose();
            }
        }

    }//GEN-LAST:event_jToggleButton1_closeActionPerformed

