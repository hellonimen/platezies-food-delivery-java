    private void loadRunnerData() {
        DefaultTableModel model = (DefaultTableModel) tableRunner.getModel();
        model.setRowCount(0);

        try (BufferedReader reader = new BufferedReader(new FileReader("platezies_txtfiles/runner.txt"))) {
            String line;
            while ((line = reader.readLine()) != null) {
                String[] data = line.split(",");
                model.addRow(data);
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, 
                                          "Error loading data from file!", 
                                          "Error", 
                                          JOptionPane.ERROR_MESSAGE);
        }
    }
    
    
