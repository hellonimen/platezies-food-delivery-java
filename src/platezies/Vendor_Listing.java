    private void jButton1_Add_Vendor_ListingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_Add_Vendor_ListingActionPerformed
        // TODO add your handling code here:
        if (!validateInputs()) {
        return; // Stop execution if validation fails
    }

    String username = tfUsername.getText().trim();
    String email = tfEmail.getText().trim();

    // Check for duplicate user (pass -1 for new entries)
    if (isDuplicateUser(username, email, -1)) {  
        JOptionPane.showMessageDialog(this, 
                                      "User with this username or email already exists!",
                                      "Duplicate Entry",
                                      JOptionPane.ERROR_MESSAGE);
        return; // Stop execution if user already exists
    }

    try {
        // Save data if validation and duplicate check pass
        saveDataToFile();
        JOptionPane.showMessageDialog(this, 
                                      "Vendor created successfully!", 
                                      "Success",
                                      JOptionPane.INFORMATION_MESSAGE);
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, 
                                      "Error saving data! Please try again.",
                                      "File Error",
                                      JOptionPane.ERROR_MESSAGE);
        Logger.getLogger(EditVendor.class.getName()).log(Level.SEVERE, null, ex);
    }
    }//GEN-LAST:event_jButton1_Add_Vendor_ListingActionPerformed

