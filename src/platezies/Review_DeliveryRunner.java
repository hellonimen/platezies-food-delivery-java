private void loadReviewDeliveryRunnerFromFile() {

        DefaultTableModel model = (DefaultTableModel) jTable1_Review_Delivery_Runner.getModel();

        model.setRowCount(0); // Clear existing rows in the table

 
        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/review_delivery_runner.txt"))) {

            String line;

            while ((line = br.readLine()) != null) {

                line = line.trim(); // Clean up any extra spaces

                String[] data = line.split(";"); // Split by comma

                if (data.length == 5) { // Ensure there are exactly 5 fields

                    String Username = data[0].trim();

                    String Name  = data[1].trim();

                    String Email = data[2].trim();

                    String contactNumber = data[3].trim();
                    
                    String averageRanking = data[4].trim();

                    // Add the row to the table

                    model.addRow(new Object[] { Username, Name, Email, contactNumber,averageRanking });

                }

            }

        } catch (IOException e) {

            e.printStackTrace();

        }

        model.fireTableDataChanged(); // Refresh the table to display updated data

    }
 

