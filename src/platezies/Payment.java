    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        // TODO add your handling code here:                       
        String selectedAmountStr = (String) jComboBox1.getSelectedItem();
        
        if (selectedAmountStr == null || selectedAmountStr.equals("-- Select Amount --")) {
            return;
        }

        try {
            double selectedAmount = Double.parseDouble(selectedAmountStr.replace("$", "").trim());
            
            if (selectedAmount < totalAmount) {
                JOptionPane.showMessageDialog(this, 
                    "Selected amount is less than the total due!\nTotal Due: $" + totalAmount + "\nSelected: $" + selectedAmount + "\nPlease top up more money.",
                    "Insufficient Funds", 
                    JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid amount format! Please select a valid amount.", "Error", JOptionPane.ERROR_MESSAGE);
        }
        validateAmount();
    }  
private void processPayment() {
    // ✅ Validate that all required fields are filled
    if (tfCardNumber.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Card Number is required!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (tfExpiryDate.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Expiry Date is required!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (tfSecurityCode.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Security Code is required!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    if (tfCardHolderName.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Cardholder Name is required!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // ✅ Validate amount selection
    Object selectedObject = jComboBox1.getSelectedItem();
    if (selectedObject == null || selectedObject.toString().equals("-- Select Amount --")) {
        JOptionPane.showMessageDialog(this, "Please select a valid amount before proceeding!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // ✅ Validate selected amount format
    double selectedAmount;
    try {
        selectedAmount = Double.parseDouble(selectedObject.toString().replace("$", "").trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid amount format! Please select a valid amount.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // ✅ Check if selected amount is less than total amount
    if (selectedAmount < totalAmount) {
        JOptionPane.showMessageDialog(this, 
            "Selected amount is less than the total due!\nTotal Due: $" + totalAmount + 
            "\nSelected: $" + selectedAmount + "\nPlease top up more money.", 
            "Insufficient Funds", JOptionPane.ERROR_MESSAGE);
        return; 
    }

    // ✅ Construct the Receipt String with proper formatting
    receiptDetails = "======== PLATEZIES ORDER RECEIPT ========\n"
                   + "Total Amount: $" + totalAmount + "\n"
                   + "Paid: $" + selectedAmount + "\n"
                   + "-------------------------------------------\n"
                   + "Order Items:\n"
                   + orderDetails.replace("|", "\n") + "\n"
                   + "-------------------------------------------\n"
                   + "Dining Option: Dine-in\n"
                   + "Status: Pending\n"
                   + "Date: 21-02-2025\n"
                   + "-------------------------------------------\n"
                   + "Thank you for ordering with Platezies!\n";

    // ✅ Debugging: Print to console to verify correct formatting
    System.out.println("Receipt Details:\n" + receiptDetails);

    // ✅ Write Payment Details to `payment.txt` File
    savePaymentToFile(totalAmount, selectedAmount, orderDetails, "Pending");

    // ✅ Display receipt window
    SwingUtilities.invokeLater(() -> {
        Generate_Receipt receiptPanel = new Generate_Receipt(receiptDetails);
        JFrame receiptFrame = new JFrame("Generate Receipt");
        receiptFrame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
        receiptFrame.add(receiptPanel);
        receiptFrame.pack();
        receiptFrame.setLocationRelativeTo(null);
        receiptFrame.setVisible(true);
    });

    // ✅ Close Payment Window AFTER Showing Receipt
    SwingUtilities.invokeLater(() -> {
        JFrame parentFrame = (JFrame) SwingUtilities.getWindowAncestor(this);
        if (parentFrame != null) {
            parentFrame.dispose();
        }
    });
}

/**
 * Save Payment Details to payment.txt
 */
private void savePaymentToFile(double totalAmount, double paidAmount, String orderDetails, String status) {
     
     try (BufferedWriter writer = new BufferedWriter(new FileWriter("platezies_txtfiles/payment.txt", true))) { // Append mode

        // Extract user details from input fields
        String cardNumber = tfCardNumber.getText().trim();
        String expiryDate = tfExpiryDate.getText().trim();
        String cardHolderName = tfCardHolderName.getText().trim();
        String securityCode = tfSecurityCode.getText().trim();
        String address = tfAddress.getText().trim();
        String city = tfCity.getText().trim();
        String postcode = tfPostcode.getText().trim();
        String state = tfState.getText().trim();

        // Format the payment record
        String paymentRecord = "Total Amount: $" + totalAmount + "\n"
                             + "Paid Amount: $" + paidAmount + "\n"
                             + "Card Number: " + cardNumber + "\n"
                             + "Expiry Date: " + expiryDate + "\n"
                             + "Cardholder Name: " + cardHolderName + "\n"
                             + "Security Code: " + securityCode + "\n"
                             + "Billing Address: " + address + ", " + city + ", " + state + ", " + postcode + "\n"
                             + "Status: " + status + "\n"
                             + "------------------------------------------\n";

        // Write to file
        writer.write(paymentRecord);
        writer.flush();

        // Show success message
        JOptionPane.showMessageDialog(this, "Payment details saved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error saving payment record!", "File Error", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
    }//GEN-LAST:event_jComboBox1ActionPerformed
