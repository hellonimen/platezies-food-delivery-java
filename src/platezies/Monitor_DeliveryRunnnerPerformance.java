    private void jButton1_Bar_ChartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_Bar_ChartActionPerformed
        // TODO add your handling code here:
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();

        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/delivery_runner_performance.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] data = line.split(";");
                if (data.length == 4) {
                    String deliveryRunnerID = data[0].trim();
                    double avgRanking = Double.parseDouble(data[3].trim()); // Corrected index to 3
                    dataset.addValue(avgRanking, "Average Ranking", deliveryRunnerID);
                }
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading delivery runner performance data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error parsing average ranking: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (dataset.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No data available for the chart.", "Information", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        JFreeChart chart = ChartFactory.createBarChart(
            "Delivery Runner Performance", "Delivery Runner ID", "Average Ranking",
            dataset, org.jfree.chart.plot.PlotOrientation.VERTICAL, false, true, false
        );

        CategoryPlot plot = chart.getCategoryPlot();
        plot.setRangeGridlinePaint(Color.BLACK);

        ChartFrame frame = new ChartFrame("Bar Chart for Delivery Runner Performance", chart);
        frame.setSize(600, 400);
        frame.setLocationRelativeTo(null); // Center the frame
        frame.setVisible(true);
    }//GEN-LAST:event_jButton1_Bar_ChartActionPerformed
class StarRatingRenderer extends DefaultTableCellRenderer {
    @Override
    public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
        if (value instanceof String) {
            try {
                int rating = Integer.parseInt((String) value); // Convert to integer
                StringBuilder stars = new StringBuilder();
                for (int i = 0; i < 5; i++) {
                    if (i < rating) {
                        stars.append("★"); // Filled star
                    } else {
                        stars.append("☆"); // Empty star
                    }
                }
                value = stars.toString(); // Display stars instead of numbers
            } catch (NumberFormatException e) {
                value = "☆☆☆☆☆"; // Default to 0 stars if an error occurs
            }
        }
        return super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
    }
}

    
    private void loadDeliveryRunnerPerformanceFromFile() {
    DefaultTableModel model = (DefaultTableModel) jTable1_Monitor_Delivery_Runner.getModel();
    model.setRowCount(0); // Clear existing rows

    try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/delivery_runner_performance.txt"))) {
        String line;
        while ((line = br.readLine()) != null) {
            line = line.trim();
            String[] data = line.split(";"); 
            if (data.length == 4) { // Ensure 4 fields exist
                String deliveryRunnerID = data[0].trim();
                String name = data[1].trim();
                String contactNumber = data[2].trim();
                String averageRanking = data[3].trim(); // Keep as string
                
                // Add row to table
                model.addRow(new Object[]{deliveryRunnerID, name, contactNumber, averageRanking});
            }
        }
    } catch (IOException e) {
        e.printStackTrace();
    }

    // Apply star rating renderer to the "Average Ranking" column (index 3)
    jTable1_Monitor_Delivery_Runner.getColumnModel().getColumn(3).setCellRenderer(new StarRatingRenderer());
    model.fireTableDataChanged(); // Refresh table
}

    

