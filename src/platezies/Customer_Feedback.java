    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:                                         
         // Display dialog box with the message
        JOptionPane.showMessageDialog(this, "Thanks for your feedback. Your issue has been resolved. Thanks for your patience.");
        
        // Remove selected row from table
        int selectedRow = jTable1_Customer_Feedback.getSelectedRow();
        if (selectedRow != -1) {
            DefaultTableModel model = (DefaultTableModel) jTable1_Customer_Feedback.getModel();
            String feedbackId = model.getValueAt(selectedRow, 0).toString();
            model.removeRow(selectedRow);
            deleteFeedbackFromFile(feedbackId);
        }                      
    }//GEN-LAST:event_jButton1ActionPerformed
    private void deleteFeedbackFromFile(String feedbackId) {
        List<String> feedbackList = new ArrayList<>();
        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/customer_complains.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] data = line.split(",");
                if (!data[0].equals(feedbackId)) {
                    feedbackList.add(line);
                }
            }
        } catch (IOException e) {
            System.err.println("Error reading file: " + e.getMessage());
        }
        
        String filePath = Paths.get("platezies_txtfiles/customer_complains.txt").toAbsolutePath().toString();
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(filePath))) {
            for (String feedback : feedbackList) {
                bw.write(feedback);
                bw.newLine();
            }
        } catch (IOException e) {
            System.err.println("Error writing file: " + e.getMessage());
        }
    }
    
    private void loadCustomerFeedbackFromFile() {
        DefaultTableModel model = (DefaultTableModel) jTable1_Customer_Feedback.getModel();
        model.setRowCount(0); // Clear existing rows

        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/customer_complains.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] data = line.split(",");
                if (data.length == 4) { // Ensure correct number of columns
                    model.addRow(data); // Append row to table
                }
            }
        } catch (IOException e) {
            System.err.println("Error reading file: " + e.getMessage());
        }
    }

