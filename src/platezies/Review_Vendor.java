private void loadReviewVendorFromFile() {

        DefaultTableModel model = (DefaultTableModel) jTable1_Review_Vendor.getModel();

        model.setRowCount(0); // Clear existing rows in the table

 
        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/reviews.txt"))) {

            String line;

            while ((line = br.readLine()) != null) {

                line = line.trim(); // Clean up any extra spaces

                String[] data = line.split(","); // Split by comma

                if (data.length == 8 ) { // Ensure there are exactly 5 fields

                    String reviewID = data[0].trim();
                    String orderItemID = data[1].trim();
                    String itemName = data[2].trim();
                    String cuisineType = data[3].trim();
                    String customerName = data[4].trim();
                    String starRanking = data[5].trim();
                    String feedback = data[6].trim();
                    String date = data[7].trim();
                    
                    // Add the row to the table

                    model.addRow(new Object[] { reviewID, orderItemID, itemName, cuisineType, customerName, starRanking, feedback, date});

                }

            }

        } catch (IOException e) {

            e.printStackTrace();

        }

        model.fireTableDataChanged(); // Refresh the table to display updated data

    }
 

