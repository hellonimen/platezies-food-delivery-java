    private void jButton1_SendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_SendActionPerformed
        // TODO add your handling code here:
                                                 
    // Collect input data
    String name = tfName.getText().trim();
        String username = tfUsername.getText().trim();
        String feedback = tfFeedback.getText().trim();

        if (name.isEmpty() || username.isEmpty() || feedback.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter all fields", "Missing Inputs", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (BufferedWriter writer = new BufferedWriter(new FileWriter("platezies_txtfiles/customer_complains.txt", true))) {
            writer.write(getNextComplaintId()+","+name + "," + username + "," + feedback);
            writer.newLine();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error saving to file!", "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
            return;
        }

        JOptionPane.showMessageDialog(this, "Your complaint has been sent to the Admin successfully!", "Complaint Sent", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_jButton1_SendActionPerformed

