    private String getNextComplaintId() {
    String filePath = "platezies_txtfiles/customer_complains.txt";
    String lastId = "C000";
    
    try (BufferedReader reader = new BufferedReader(new FileReader(filePath))) {
        String line;
        while ((line = reader.readLine()) != null) {
            if (!line.isEmpty()) {
                lastId = line.split(",")[0];
            }
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error reading Complaints.txt!", "File Error", JOptionPane.ERROR_MESSAGE);
    }
    
    int nextIdNumber = Integer.parseInt(lastId.substring(1)) + 1;
    return "C" + String.format("%03d", nextIdNumber);
}

