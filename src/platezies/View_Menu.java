    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       // TODO add your handling code here:                                                                                                                    
                                        
    String totalText = jTextField2_Total_Sum.getText().replace("$", "").trim();
    if (totalText.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Total amount is missing!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    double totalAmount;
    try {
        totalAmount = Double.parseDouble(totalText);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "Invalid total amount!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    StringBuilder orderDetails = new StringBuilder("Order Summary:\n");
    DefaultTableModel receiptModel = (DefaultTableModel) jTable1_ViewMenu1.getModel();

    if (receiptModel == null) {
        JOptionPane.showMessageDialog(null, "Error: Receipt table is not initialized!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    for (int i = 0; i < receiptModel.getRowCount(); i++) {
        String cuisine = receiptModel.getValueAt(i, 0).toString();
        String itemName = receiptModel.getValueAt(i, 1).toString();
        String price = receiptModel.getValueAt(i, 2).toString();
        orderDetails.append(cuisine).append(" - ").append(itemName).append(" | Price: ").append(price).append("\n");
    }

    orderDetails.append("\nTotal Amount: $").append(totalAmount);
    orderDetails.append("\nDining Option: ").append(jComboBox1.getSelectedItem().toString());
    orderDetails.append("\nStatus: pending");
    orderDetails.append("\nDate: ").append(new SimpleDateFormat("dd-MM-yyyy").format(new Date()));

    // ✅ **SHOW MESSAGE FOR TOP-UP CONFIRMATION**
    int topUp = JOptionPane.showConfirmDialog(this, 
            "Please top up an amount greater than $" + totalAmount + " before proceeding.", 
            "Top-up Required", 
            JOptionPane.OK_CANCEL_OPTION, 
            JOptionPane.WARNING_MESSAGE);

    if (topUp != JOptionPane.OK_OPTION) {
        return; // If user cancels, stop the process
    }

    // ✅ **Open Payment Window & Pass Order Details**
    Payment payment = new Payment(totalAmount, orderDetails.toString());
    
    JFrame frame = new JFrame("Payment");
    frame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
    frame.add(payment);
    frame.pack();
    frame.setLocationRelativeTo(null);
    frame.setVisible(true);
    }//GEN-LAST:event_jButton1ActionPerformed
private void loadVendorListingFromFile() {
    
 File menuFile = new File("platezies_txtfiles/menu.txt"); // Update the path as per your project
    if (menuFile.exists()) {
        try (BufferedReader reader = new BufferedReader(new FileReader(menuFile))) {
            DefaultTableModel model = (DefaultTableModel) jTable1_ViewMenu.getModel();
            String line;
            while ((line = reader.readLine()) != null) {
                String[] parts = line.split(",");
                if (parts.length >= 5) {
                    String cuisine = parts[0].trim();
                    String foodName = parts[1].trim();
                    String price = parts[3].trim();
                    String imagePath = parts[4].trim();

                    model.addRow(new Object[]{cuisine, foodName, "$" + price, imagePath});
                }
            }
        } catch (IOException e) {
            e.printStackTrace();
        }
    }
}

   
    
    
private static class ImageRenderer extends javax.swing.table.DefaultTableCellRenderer {
    @Override
    public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
        JLabel label = new JLabel();
        label.setHorizontalAlignment(JLabel.CENTER);
        if (value != null && value.toString().trim().length() > 0 && !value.toString().equalsIgnoreCase("null")) {
            File imgFile = new File(value.toString());
            if (imgFile.exists()) {
                ImageIcon icon = new ImageIcon(value.toString());
                Image scaledImage = icon.getImage().getScaledInstance(50, 50, Image.SCALE_SMOOTH);
                label.setIcon(new ImageIcon(scaledImage));
            } else {
                label.setText("Image not found");
            }
        } else {
            label.setText("No image");
        }
        return label;
    }
}

private void addMenuItemToReceipt() {
        int selectedRow = jTable1_ViewMenu.getSelectedRow();
        if (selectedRow != -1) {
            DefaultTableModel receiptModel = (DefaultTableModel) jTable1_ViewMenu1.getModel();
            receiptModel.addRow(new Object[]{
                jTable1_ViewMenu.getValueAt(selectedRow, 0),
                jTable1_ViewMenu.getValueAt(selectedRow, 1),
                jTable1_ViewMenu.getValueAt(selectedRow, 2)
            });
            updateTotalSum();
        }
    }

private void updateTotalSum() {
        double total = 0;
        DefaultTableModel receiptModel = (DefaultTableModel) jTable1_ViewMenu1.getModel();
        for (int i = 0; i < receiptModel.getRowCount(); i++) {
            total += Double.parseDouble(receiptModel.getValueAt(i, 2).toString().replace("$", "").trim());
        }
        jTextField2_Total_Sum.setText(String.format("$%.2f", total));
    }




private void removeItemFromReceipt() {
    // Get the selected row index from the receipt table
    int selectedRow = jTable1_ViewMenu1.getSelectedRow();
    if (selectedRow != -1) {
        // Remove the selected row from the table model
        DefaultTableModel receiptModel = (DefaultTableModel) jTable1_ViewMenu1.getModel();
        receiptModel.removeRow(selectedRow);

        // Optionally update the total sum after removing the item
        updateTotalSum();
    } else {
        // Show an error message if no row is selected
        JOptionPane.showMessageDialog(null, "Please select an item to remove.", "No Selection", JOptionPane.WARNING_MESSAGE);
    }
}

public class OrderManager {
    
    private static final String ORDER_FILE = Paths.get("platezies_txtfiles/Orders.txt").toAbsolutePath().toString();
    private static final String ITEM_ORDER_FILE = Paths.get("platezies_txtfiles/OrderItem.txt").toAbsolutePath().toString();
    // Method to get the next Order ID
    public static String getNextOrderId() {
        String lastOrderId = "000"; // Default if no orders exist
        try (BufferedReader br = new BufferedReader(new FileReader(ORDER_FILE))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] parts = line.split(",");
                if (parts.length > 0) {
                    lastOrderId = parts[0]; // Get last order ID
                }
            }
        } catch (IOException e) {
            e.printStackTrace();
        }
        
        // Convert lastOrderId to integer, increment, and format back to 3-digit string
        int nextId = Integer.parseInt(lastOrderId) + 1;
        return String.format("%03d", nextId); // Ensures format like 001, 002, etc.
    }
    
    public static String getNextItemOrderId() {
        return UUID.randomUUID().toString();
    }
}



