    private void jButton1_Reoder_Food_ItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_Reoder_Food_ItemActionPerformed
        // TODO add your handling code here:                                         
    // ✅ Validate if a row is selected
    int selectedRow = jTable1_Order_History.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select an order to reorder.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // ✅ Retrieve selected order details
    DefaultTableModel model = (DefaultTableModel) jTable1_Order_History.getModel();
    String orderItemID = model.getValueAt(selectedRow, 0).toString();
    String orderID = model.getValueAt(selectedRow, 1).toString();
    String customerName = model.getValueAt(selectedRow, 2).toString();
    String cuisineType = model.getValueAt(selectedRow, 3).toString();
    String itemName = model.getValueAt(selectedRow, 4).toString();
    String diningOptions = model.getValueAt(selectedRow, 5).toString();
    String cost = model.getValueAt(selectedRow, 6).toString();
    String price = model.getValueAt(selectedRow, 7).toString(); // Price in string format
    String status = "Pending"; // Change status to pending
    String date = java.time.LocalDate.now().toString(); // Get today's date

    // ✅ Append reordered item to OrderItem.txt
    try (BufferedWriter bw = new BufferedWriter(new FileWriter("platezies_txtfiles/OrderItem.txt", true))) {
        String newOrder = UUID.randomUUID().toString() + "," + orderID + "," + customerName + "," + cuisineType + "," + 
                          itemName + "," + diningOptions + "," + cost + "," + price + "," + status + "," + date;
        bw.write(newOrder);
        bw.newLine();
    } catch (IOException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error saving reordered item.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    JOptionPane.showMessageDialog(this, "Reorder successful! Redirecting to payment page.", "Success", JOptionPane.INFORMATION_MESSAGE);

    // ✅ Fix: Convert price to double before passing to Payment
    double totalAmount;
    try {
        totalAmount = Double.parseDouble(price.replace("$", "").trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid price format.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // ✅ Construct order details before passing to Payment
    String orderDetails = "Reordered Item: " + itemName + " | Cuisine Type: " + cuisineType + " | Dining Option: " + diningOptions + " | Price: $" + price;

    // ✅ Corrected Payment constructor call
    Payment payment = new Payment(totalAmount, orderDetails);

    // ✅ Create a new JFrame for the Payment Page
    JFrame frame = new JFrame("Payment");
    frame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
    frame.add(payment);
    frame.pack();
    frame.setLocationRelativeTo(null);
    frame.setVisible(true);
    }//GEN-LAST:event_jButton1_Reoder_Food_ItemActionPerformed
private void loadOrderHistoryFromFile() {
    DefaultTableModel model = (DefaultTableModel) jTable1_Order_History.getModel();
    model.setRowCount(0); // Clear existing rows in the table

   try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/OrderItem.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                line = line.trim(); // Clean up any extra spaces
                String[] data = line.split(","); // Split by comma
                if (data.length == 10) { // Ensure there are exactly 5 fields
                    String orderItemID= data[0].trim();
                    String orderID= data[1].trim();
                    String customerName = data[2].trim();
                    String cuisineType = data[3].trim();
                    String itemName = data[4].trim();
                    String diningOptions = data[5].trim();
                    String cost=data[6].trim();
                    String price= data[7].trim();
                    String status = data[8].trim();
                    String date= data[9].trim();
                    // Add the row to the table
                // Only add completed orders
                if ("completed".equals(status)) {
                     model.addRow(new Object[] { orderItemID, orderID, customerName, cuisineType, itemName, diningOptions, cost, price, status, date });
                }
            }
        }
    } catch (IOException e) {
        e.printStackTrace();
    }
    
    model.fireTableDataChanged(); // Refresh the table to display updated data
}


