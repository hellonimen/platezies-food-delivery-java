private void loadOrderStatusFromFile() {
        DefaultTableModel model = (DefaultTableModel) jTable3_Order_History.getModel();
        model.setRowCount(0); // Clear existing rows in the table

 
        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/OrderItem.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                line = line.trim(); // Clean up any extra spaces
                String[] data = line.split(","); // Split by comma
                if (data.length == 10) { // Ensure there are exactly 5 fields
                    String orderItemID= data[0].trim();
                    String orderID= data[1].trim();
                    String customerName = data[2].trim();
                    String cuisineType = data[3].trim();
                    String itemName = data[4].trim();
                    String diningOptions = data[5].trim();
                    String cost=data[6].trim();
                    String price= data[7].trim();
                    String status = data[8].trim();
                    String date= data[9].trim();
                    // Add the row to the table
                    model.addRow(new Object[] { orderItemID, orderID, customerName, cuisineType, itemName, diningOptions, cost, price, status, date });
                }
            }
        } catch (IOException e) {
            e.printStackTrace();
        }
        model.fireTableDataChanged(); // Refresh the table to display updated data
    }

