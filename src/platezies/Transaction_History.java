private void loadTransactionHistoryFromFile() {
    DefaultTableModel model = (DefaultTableModel) jTable1_Transaction_History.getModel();
    model.setRowCount(0); // Clear existing rows in the table

    try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/payment.txt"))) {
        String line;
        while ((line = br.readLine()) != null) {
            line = line.trim(); // Clean up extra spaces
            
            // ✅ Look for "Total Amount:" to identify the start of a transaction
            if (line.startsWith("Total Amount:")) {
                String totalAmount = line.replace("Total Amount: $", "").trim(); // Extract Total Amount
                
                // ✅ Read the next line for "Paid Amount:" (Top-Up Credit)
                String paidAmountLine = br.readLine().trim();
                String topUpCredit = paidAmountLine.replace("Paid Amount: $", "").trim(); 

                br.readLine(); // Skip "Card Number"
                br.readLine(); // Skip "Expiry Date"
                
                // ✅ Read the correct "Cardholder Name"
                String cardHolderNameLine = br.readLine().trim();
                String cardHolderName = cardHolderNameLine.replace("Cardholder Name:", "").trim();

                br.readLine(); // Skip "Security Code"
                br.readLine(); // Skip "Billing Address"

                // ✅ Read "Status"
                String statusLine = br.readLine().trim();
                String status = statusLine.replace("Status:", "").trim();

                // ✅ Add only valid transactions
                if (!topUpCredit.isEmpty() && !cardHolderName.isEmpty() && !status.isEmpty()) {
                    model.addRow(new Object[]{topUpCredit, cardHolderName, status});
                }
            }
        }
    } catch (IOException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error reading payment history.", "Error", JOptionPane.ERROR_MESSAGE);
    }

    model.fireTableDataChanged(); // Refresh the table to display updated data
}







