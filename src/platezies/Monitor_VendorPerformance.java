    private void jButton1_BarChartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_BarChartActionPerformed
        // TODO add your handling code here:
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();

        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/revenue.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] data = line.split(",");
                if (data.length == 8) {
                    String stallName = data[1].trim();
                    double starRanking = Double.parseDouble(data[5].trim());
                    dataset.addValue(starRanking, "Star Ranking", stallName);
                }
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading vendor performance data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error parsing average ranking: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (dataset.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No data available for the chart.", "Information", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        JFreeChart chart = ChartFactory.createBarChart(
            "Vendor Performance", "Stall Name", "Star Ranking",
            dataset, org.jfree.chart.plot.PlotOrientation.VERTICAL, false, true, false
        );

        CategoryPlot plot = chart.getCategoryPlot();
        plot.setRangeGridlinePaint(Color.BLACK);

        ChartFrame frame = new ChartFrame("Bar Chart for Vendor Performance", chart);
        frame.setSize(600, 400);
        frame.setLocationRelativeTo(null); 
        frame.setVisible(true);
    }//GEN-LAST:event_jButton1_BarChartActionPerformed

    private void jButton1_Linear_ChartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1_Linear_ChartActionPerformed
        // TODO add your handling code here:                                                     
    // Create a dataset for the linear chart
    DefaultCategoryDataset dataset = new DefaultCategoryDataset();

    // Read the vendor performance data from the file
    try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/revenue.txt"))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] data = line.split(",");
            if (data.length == 8) {
                String stallName = data[1].trim();
                double profit = Double.parseDouble(data[4].trim()); // Parse profit as double
                String month = data[6].trim();
                String year = data[7].trim();
                String timePeriod = month + "-" + year; // Combine month and year to create a unique time period

                // Add profit data to dataset, where "Profit" is the series name and the timePeriod is the X-axis
                dataset.addValue(profit, "Profit", timePeriod);
            }
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error reading vendor performance data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        return;
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Error parsing profit data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Check if dataset is empty
    if (dataset.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "No data available for the chart.", "Information", JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    // Create the line chart
    JFreeChart chart = ChartFactory.createLineChart(
        "Vendor Profit Over Time", // Chart Title
        "Time Period", // X-axis Label
        "Profit", // Y-axis Label
        dataset, // Dataset
        org.jfree.chart.plot.PlotOrientation.VERTICAL, // Chart orientation
        true, // Include legend
        true, // Tooltips enabled
        false // URLs disabled
    );

    // Customize the chart appearance
    chart.setBackgroundPaint(Color.white);

    // Create a chart frame to display the chart
    ChartFrame frame = new ChartFrame("Profit Linear Chart", chart);
    frame.setSize(800, 600);
    frame.setLocationRelativeTo(null); // Center the chart frame on the screen
    frame.setVisible(true);

    }//GEN-LAST:event_jButton1_Linear_ChartActionPerformed
class StarRatingRenderer extends DefaultTableCellRenderer {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
            if (value instanceof String) {
                try {
                    int rating = Integer.parseInt((String) value); 
                    StringBuilder stars = new StringBuilder();
                    for (int i = 0; i < 5; i++) {
                        if (i < rating) {
                            stars.append("★"); 
                        } else {
                            stars.append("☆"); 
                        }
                    }
                    value = stars.toString(); 
                } catch (NumberFormatException e) {
                    value = "☆☆☆☆☆"; 
                }
            }
            return super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
        }
    }

    private void loadVendorPerformanceFromFile() {
        DefaultTableModel model = (DefaultTableModel) jTable1_Monitor_Vendor_Performance.getModel();
        model.setRowCount(0);

        try (BufferedReader br = new BufferedReader(new FileReader("platezies_txtfiles/revenue.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                line = line.trim();
                String[] data = line.split(",");
                if (data.length == 8) { 
                    String email = data[0].trim();
                    String stallName = data[1].trim();
                    String contactNumber = data[2].trim();
                    String revenue = data[3].trim();
                    String profit = data[4].trim();
                    String starRanking = data[5].trim(); 
                    String month = data[6].trim();
                    String year = data[7].trim();
                    model.addRow(new Object[]{email, stallName, contactNumber, revenue, profit, starRanking, month, year});
                }
            }
        } catch (IOException e) {
            e.printStackTrace();
        }

        jTable1_Monitor_Vendor_Performance.getColumnModel().getColumn(5).setCellRenderer(new StarRatingRenderer());
        model.fireTableDataChanged();
    }


